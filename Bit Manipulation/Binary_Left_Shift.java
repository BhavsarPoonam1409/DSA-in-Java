public class Binary_Left_Shift {
    public static void main(String[] args) {
        
        //mutiply thse left
        //divide in right
        System.out.println(5<<1); //10 5*2
        System.out.println(4<<1); //8 4*2

        System.out.println();
        System.out.println(5<<2); // 5*4
        System.out.println(4<<2); //4*4

        System.out.println();
        System.out.println(5<<3); //5*8
        System.out.println(4<<3); //4*8
    }
}
